  'emptyCount',CAST((SELECT COUNT(*) FROM (SELECT 1 AS value) AS invented WHERE 1=0) AS UNSIGNED),
  'scalarText',CAST((SELECT '1') AS UNSIGNED),
  'nested',JSON_QUERY((SELECT JSON_OBJECT('host','172.21.0.1','locked',CASE WHEN 1=1 THEN 1 ELSE 0 END,'accessZero',CASE WHEN CAST('0' AS UNSIGNED)=0 THEN 1 ELSE 0 END,'requiresSsl',CASE WHEN 'ANY'='ANY' THEN 1 ELSE 0 END,'noPassword',CASE WHEN ''='' THEN 1 ELSE 0 END,'noAlternateAuth',CASE WHEN JSON_EXTRACT('{}','$.auth_or') IS NULL THEN 1 ELSE 0 END,'plugin','mysql_native_password','maxUserConnections',CAST('1' AS UNSIGNED))),'$'),
  'nullObject',JSON_QUERY((SELECT JSON_OBJECT('unused',1) WHERE 1=0),'$')
 )
);
